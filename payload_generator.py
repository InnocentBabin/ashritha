import json
import re
import logging
from typing import Dict, List, Optional, Any
from datetime import datetime

try:
    import ollama
    OLLAMA_AVAILABLE = True
except ImportError:
    OLLAMA_AVAILABLE = False
    print("⚠️ Ollama not installed. Run: pip install ollama")

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class PayloadGenerator:
    """
    LLM-driven payload generator.
    Every payload is generated by the local Ollama model based on:
      - The vulnerability type
      - The endpoint + parameter
      - The actual server response received
      - Previous attempts (iterative refinement)
    """

    def __init__(self, model_name: str = "llama3.1:8b", host: str = None):
        self.model_name = model_name
        self.host = host or "http://localhost:11434"
        self.client = None
        self.generated_payloads = []
        self.history = {}  # key: (endpoint, param, vtype), value: list of attempts

        if OLLAMA_AVAILABLE:
            try:
                self.client = ollama.Client(host=self.host)
                self.client.list()
                logger.info(f"✅ LLM Payload Generator connected → {self.host} ({self.model_name})")
            except Exception as e:
                logger.error(f"❌ Ollama connection failed: {e}")
                self.client = None

    # ============================================================
    # MAIN ENTRY — generate a payload
    # ============================================================
    def generate_payload(
        self,
        vulnerability_type: str,
        endpoint: str,
        parameter: str,
        method: str,
        server_response: str,
        previous_attempts: Optional[List[Dict]] = None,
        context: Optional[Dict] = None,
    ) -> Optional[Dict]:
        """
        Generate one custom payload based on the actual server response.
        Returns dict with keys: payload, description, expected_marker, confidence, explanation, curl
        """
        if not self.client:
            logger.error("LLM not available — cannot generate payload")
            return None

        # Truncate huge responses to keep the prompt efficient
        response_snippet = self._truncate_response(server_response, max_len=4000)
        analysis = self._analyze_response(response_snippet, vulnerability_type)

        prompt = self._build_prompt(
            vulnerability_type=vulnerability_type,
            endpoint=endpoint,
            parameter=parameter,
            method=method,
            response_analysis=analysis,
            response_snippet=response_snippet,
            previous_attempts=previous_attempts or [],
            context=context or {},
        )

        logger.info(f"🧠 LLM generating {vulnerability_type} payload for {endpoint} [{parameter}]")

        try:
            response = self.client.chat(
                model=self.model_name,
                messages=[
                    {"role": "system", "content": self._system_prompt(vulnerability_type)},
                    {"role": "user", "content": prompt},
                ],
                options={"temperature": 0.4},
            )
            raw = response.message.content.strip()
            parsed = self._parse_llm_response(raw)

            if not parsed:
                logger.warning("LLM response could not be parsed")
                return None

            parsed.update({
                "vulnerability_type": vulnerability_type,
                "endpoint": endpoint,
                "parameter": parameter,
                "method": method,
                "generated_by": "LLM",
                "timestamp": datetime.now().isoformat(),
                "curl": self._make_curl(endpoint, parameter, parsed.get("payload", ""), method),
            })

            # Track history
            key = (endpoint, parameter, vulnerability_type)
            self.history.setdefault(key, []).append(parsed)
            self.generated_payloads.append(parsed)

            logger.info(f"✅ LLM payload: {parsed.get('payload', '')[:80]}")
            return parsed

        except Exception as e:
            logger.error(f"LLM payload generation failed: {e}")
            return None

    # ============================================================
    # PROMPTS
    # ============================================================
    def _system_prompt(self, vtype: str) -> str:
        """Specialized system prompt per vulnerability type."""
        base = (
            "You are an elite penetration tester AI. You analyze real HTTP server "
            "responses and craft targeted attack payloads. You think step-by-step but "
            "reply with STRICT JSON ONLY — no prose outside the JSON object."
        )

        per_type = {
            "sql_injection": (
                " You specialize in SQL injection. Analyze error messages, database "
                "fingerprints, and response structure. Craft payloads that will either "
                "trigger a database error, cause a measurable time delay, or change the "
                "response in a boolean-detectable way. Prefer payloads tailored to the "
                "specific database engine you identify from the response."
            ),
            "xss": (
                " You specialize in XSS. Analyze where input is reflected (attribute, "
                "text, script block). Craft payloads that will execute JavaScript in "
                "that specific context — breaking out of the current context if needed."
            ),
            "command_injection": (
                " You specialize in OS command injection. Identify the OS from the "
                "response (headers, error text, file paths). Craft payloads that "
                "execute a harmless command whose output will appear in the response."
            ),
            "path_traversal": (
                " You specialize in path traversal. Based on server headers and errors, "
                "determine whether it's Linux or Windows. Craft payloads that read a "
                "known file whose contents will be returned."
            ),
            "ssti": (
                " You specialize in Server-Side Template Injection. Identify the template "
                "engine from the response if possible (Jinja2, Twig, Freemarker, etc.). "
                "Craft a payload that evaluates a mathematical expression to confirm SSTI."
            ),
            "idor": (
                " You specialize in IDOR and access control flaws. Based on the response "
                "and URL structure, craft an ID or parameter value that would access a "
                "resource belonging to another user."
            ),
            "broken_access_control": (
                " You specialize in broken access control. Based on the response and "
                "endpoint, craft a request that would bypass authorization — e.g., "
                "accessing an admin path, changing a role parameter, or adding privileged "
                "query parameters."
            ),
        }
        return base + per_type.get(vtype, "")

    def _build_prompt(
        self,
        vulnerability_type: str,
        endpoint: str,
        parameter: str,
        method: str,
        response_analysis: Dict,
        response_snippet: str,
        previous_attempts: List[Dict],
        context: Dict,
    ) -> str:

        prev_block = ""
        if previous_attempts:
            lines = []
            for i, a in enumerate(previous_attempts[-5:], 1):
                lines.append(
                    f"  Attempt {i}:\n"
                    f"    Payload: {a.get('payload', '')}\n"
                    f"    Result: {a.get('result', 'no effect')}"
                )
            prev_block = "PREVIOUS ATTEMPTS (learn from these):\n" + "\n".join(lines) + "\n\n"

        return f"""Generate ONE custom {vulnerability_type} payload for the target below.

TARGET:
  URL:       {endpoint}
  Method:    {method}
  Parameter: {parameter}
  Vulnerability: {vulnerability_type}

SERVER RESPONSE ANALYSIS:
  HTTP Status:       {response_analysis.get('status_code', 'unknown')}
  Response Length:   {response_analysis.get('length', 0)} bytes
  Content-Type:      {response_analysis.get('content_type', 'unknown')}
  Server header:     {response_analysis.get('server', 'unknown')}
  Detected engine:   {response_analysis.get('engine', 'unknown')}
  Error indicators:  {', '.join(response_analysis.get('errors', [])) or 'none'}
  Framework hints:   {', '.join(response_analysis.get('frameworks', [])) or 'none'}

ACTUAL SERVER RESPONSE (truncated to 4000 chars):
\"\"\"
{response_snippet}
\"\"\"

{prev_block}ADDITIONAL CONTEXT:
  {json.dumps(context, indent=2) if context else 'none'}

YOUR TASK:
Analyze the real response. Based on what the server actually returned, craft ONE payload that:
  - Is tailored to the detected technology / behavior
  - Will produce a clear, verifiable indicator if the vulnerability exists
  - Avoids patterns the previous attempts already tried

REPLY WITH THIS JSON ONLY:
{{
  "payload": "<the exact payload string>",
  "description": "<what this payload does, one sentence>",
  "expected_marker": "<exact substring that should appear in the response if vulnerable>",
  "confidence": <0.0-1.0>,
  "explanation": "<why you chose this based on the response analysis>",
  "attack_vector": "<one sentence — how this exploits the target>"
}}
"""

    def _parse_llm_response(self, raw: str) -> Optional[Dict]:
        """Extract JSON from LLM output, tolerate prose around it."""
        # Try direct JSON
        try:
            return json.loads(raw)
        except Exception:
            pass

        # Try fenced JSON
        m = re.search(r"```(?:json)?\s*(\{[\s\S]*?\})\s*```", raw)
        if m:
            try:
                return json.loads(m.group(1))
            except Exception:
                pass

        # Try first balanced object
        start = raw.find("{")
        end = raw.rfind("}")
        if start != -1 and end != -1 and end > start:
            try:
                return json.loads(raw[start:end + 1])
            except Exception:
                pass

        # Fallback: extract fields with regex
        payload_match = re.search(r'"payload"\s*:\s*"([^"]+)"', raw)
        if payload_match:
            return {
                "payload": payload_match.group(1).replace("\\\"", '"').replace("\\'", "'"),
                "description": "LLM-generated (unparsed JSON)",
                "expected_marker": "",
                "confidence": 0.5,
                "explanation": "Fallback parse",
                "attack_vector": "",
            }

        return None

    # ============================================================
    # RESPONSE ANALYSIS (fed to LLM)
    # ============================================================
    def _analyze_response(self, text: str, vtype: str) -> Dict:
        """Extract high-signal features from the response for the LLM prompt."""
        analysis = {
            "length": len(text),
            "status_code": None,
            "content_type": None,
            "server": None,
            "engine": None,
            "errors": [],
            "frameworks": [],
        }

        low = text.lower()

        # DB engines
        if any(k in low for k in ["mysql", "mariadb"]):
            analysis["engine"] = "mysql"
        elif any(k in low for k in ["postgresql", "postgres"]):
            analysis["engine"] = "postgresql"
        elif any(k in low for k in ["microsoft sql server", "mssql", "odbc sql"]):
            analysis["engine"] = "mssql"
        elif "oracle" in low:
            analysis["engine"] = "oracle"
        elif "sqlite" in low:
            analysis["engine"] = "sqlite"

        # Errors
        for pattern in [
            r"sql syntax[^\n]{0,80}",
            r"unclosed quotation[^\n]{0,80}",
            r"warning:\s*mysql[^\n]{0,80}",
            r"odbc[^\n]{0,80}",
            r"ora-\d+[^\n]{0,80}",
            r"exception[^\n]{0,80}",
            r"traceback[^\n]{0,80}",
            r"stack trace[^\n]{0,80}",
            r"fatal error[^\n]{0,80}",
        ]:
            m = re.search(pattern, text, re.IGNORECASE)
            if m:
                analysis["errors"].append(m.group(0)[:120])

        # Frameworks
        for fw in ["django", "flask", "rails", "laravel", "spring", "express",
                   "asp.net", "php", "node", "react", "angular", "vue"]:
            if fw in low:
                analysis["frameworks"].append(fw)

        # Server / content type
        for line in text.split("\n")[:30]:
            if "server:" in line.lower():
                analysis["server"] = line.split(":", 1)[1].strip()
            if "content-type:" in line.lower():
                analysis["content_type"] = line.split(":", 1)[1].strip()

        return analysis

    def _truncate_response(self, text: str, max_len: int = 4000) -> str:
        """Smart truncation: keep first N chars and error regions."""
        if len(text) <= max_len:
            return text

        head = text[: max_len // 2]
        # Try to include any region around common error keywords
        low = text.lower()
        for kw in ["error", "exception", "sql", "warning", "traceback"]:
            idx = low.find(kw)
            if idx != -1:
                start = max(0, idx - 500)
                end = min(len(text), idx + 1500)
                return head + "\n...[middle truncated]...\n" + text[start:end]

        tail = text[-max_len // 2:]
        return head + "\n...[middle truncated]...\n" + tail

    # ============================================================
    # CURL HELPER
    # ============================================================
    def _make_curl(self, endpoint: str, param: str, payload: str, method: str) -> str:
        from urllib.parse import urlparse, parse_qs, urlencode, quote
        if method.upper() == "GET":
            parsed = urlparse(endpoint)
            params = parse_qs(parsed.query)
            params[param] = [payload]
            q = urlencode(params, doseq=True, quote_via=quote)
            return f"curl -X GET '{parsed.scheme}://{parsed.netloc}{parsed.path}?{q}'"
        return f"curl -X POST '{endpoint}' -d '{param}={payload}' --data-urlencode"

    # ============================================================
    # ITERATIVE GENERATION — multi-round refinement
    # ============================================================
    def generate_iterative(
        self,
        vulnerability_type: str,
        endpoint: str,
        parameter: str,
        method: str,
        get_response,       # callable(payload) -> (response_text, status_code, elapsed)
        max_rounds: int = 5,
    ) -> Optional[Dict]:
        """
        Generate → send → analyze → regenerate (up to max_rounds).
        Returns the first payload that produced a verifiable hit.
        """
        baseline = get_response("__baseline__")[0]

        attempts = []
        for round_num in range(1, max_rounds + 1):
            logger.info(f"🔄 LLM attack round {round_num}/{max_rounds} for {vulnerability_type}")

            # First round: baseline analysis. Later rounds: use last response.
            seed_response = baseline if round_num == 1 else attempts[-1]["response"]

            payload_data = self.generate_payload(
                vulnerability_type=vulnerability_type,
                endpoint=endpoint,
                parameter=parameter,
                method=method,
                server_response=seed_response,
                previous_attempts=attempts,
                context={"round": round_num},
            )
            if not payload_data:
                logger.warning(f"Round {round_num}: LLM produced no payload")
                break

            payload = payload_data.get("payload", "")
            if not payload or payload == "__baseline__":
                break

            response_text, status, elapsed = get_response(payload)

            hit, reason = self._verify(
                vulnerability_type,
                payload_data.get("expected_marker", ""),
                payload,
                response_text,
                baseline,
                elapsed,
            )

            attempts.append({
                "payload": payload,
                "response": response_text,
                "status": status,
                "elapsed": elapsed,
                "hit": hit,
                "result": reason if hit else "no effect",
            })

            if hit:
                payload_data["success"] = True
                payload_data["evidence"] = reason
                payload_data["response_preview"] = response_text[:500]
                payload_data["response_status"] = status
                return payload_data

            logger.info(f"  ↳ round {round_num}: no hit ({reason or 'no signal'})")

        logger.warning(f"LLM attack exhausted after {len(attempts)} rounds — no exploit confirmed")
        return None

    def _verify(
        self,
        vtype: str,
        expected_marker: str,
        payload: str,
        response: str,
        baseline: str,
        elapsed: float,
    ) -> (bool, str):
        """Verify whether the LLM payload produced a vulnerability signal."""
        low = response.lower()
        base_low = baseline.lower()

        if vtype == "sql_injection":
            for pat in ["sql syntax", "unclosed quotation", "mysql", "odbc",
                        "ora-", "postgresql", "sqlite", "you have an error"]:
                if pat in low and pat not in base_low:
                    return True, f"SQL error appeared: {pat}"
            if elapsed and elapsed >= 4.0:
                return True, f"Time delay detected: {elapsed:.1f}s"
            # Response length change >40%
            if len(baseline) and abs(len(response) - len(baseline)) / len(baseline) > 0.4:
                return True, "Response size changed drastically"

        if vtype == "xss":
            if expected_marker and expected_marker in response and payload in response:
                return True, f"XSS marker reflected unencoded: {expected_marker}"
            if "<script>" in payload and "<script>" in response:
                return True, "Script tag reflected unencoded"

        if vtype == "command_injection":
            for mk in ["uid=", "gid=", "root:", "[fonts]", "bytes from", "\\"]:
                if mk in response and mk not in baseline:
                    return True, f"Command output detected: {mk}"

        if vtype == "path_traversal":
            for mk in ["root:x:", "[fonts]", "daemon:x:", "bin:x:"]:
                if mk in response and mk not in baseline:
                    return True, f"File content leaked: {mk}"

        if vtype == "ssti":
            if "49" in response and "{{" not in response and "{%" not in response:
                return True, "SSTI evaluated (49 returned)"

        if vtype in ("idor", "broken_access_control"):
            if "200" in str(response[:200]) or (len(response) > 200 and len(response) != len(baseline)):
                return True, "Unauthorized resource returned content"

        return False, ""
